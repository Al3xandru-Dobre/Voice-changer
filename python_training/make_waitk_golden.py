#!/usr/bin/env python3
"""Write the Stage 04 golden Wait-k trajectories to tests/data/waitk/.

fvml/waitk_policy.py and its C++ twin src/pipeline/WaitKPolicy.hpp are both
tested against tests/data/waitk/golden_trajectories.txt
(python_training/tests/test_waitk_policy.py, tests/test_waitk_policy.cpp), so the
two state machines cannot drift apart even in builds without a Python
environment.

One trajectory per line, 16 space-separated fields:

  k adaptive extra_wait tail_flush_ms max_flush_ratio max_flush_steps
  readiness_threshold elapsed_ms steps set_k          <- input  (10 fields)
  decisions t_src t_tgt flushes resumes checksum      <- output (6 fields)

  steps      one char per chunk step: chr(48 + speech | q << 1 | eos << 4), with
             readiness = 2 * q / 7 and `eos` flagging the step's first target chunk
  set_k      "-" or "step=k,step=k": set_k(k) before that step (k unclamped)
  decisions  one char per step: R read, W one write, X two writes, F flush
  checksum   rolling hash of (t_src, t_tgt, flushes) after every step

Standard library only. The trajectories come from random.Random(SEED), whose
sequence is stable across Python versions for the methods used.

Usage:
    make_waitk_golden.py            # (re)write tests/data/waitk/
    make_waitk_golden.py --check    # exit 1 if the file differs from a fresh run
"""
import argparse
import random
import sys
from pathlib import Path

from fvml import waitk_policy as W

OUT_PATH = Path(__file__).resolve().parent.parent / "tests" / "data" / "waitk" / "golden_trajectories.txt"
SEED = 20261114
COUNT = 256

HEADER = """\
# Wait-k policy golden trajectories (Milestone 3 / Stage 04).
# Generated by python_training/make_waitk_golden.py - do not edit by hand.
# Fields: k adaptive extra_wait tail_flush_ms max_flush_ratio max_flush_steps
#         readiness_threshold elapsed_ms steps set_k | decisions t_src t_tgt
#         flushes resumes checksum
"""


def build() -> str:
    rng = random.Random(SEED)
    lines = [HEADER]
    for _ in range(COUNT):
        traj = W.random_trajectory(rng)
        lines.append(f"{traj.header()} {W.replay(traj).footer()}\n")
    return "".join(lines)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if the committed file differs from a fresh run")
    args = ap.parse_args(argv)
    text = build()
    if args.check:
        current = OUT_PATH.read_text(encoding="ascii") if OUT_PATH.exists() else None
        if current != text:
            print(f"{OUT_PATH} is stale: rerun make_waitk_golden.py", file=sys.stderr)
            return 1
        print(f"{OUT_PATH}: up to date ({COUNT} trajectories)")
        return 0
    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text(text, encoding="ascii", newline="\n")
    print(f"wrote {OUT_PATH} ({COUNT} trajectories, {len(text)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
